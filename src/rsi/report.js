// RSI.md: the recursive self-improvement rounds, generated from rsi/ only (no hand-typed numbers).
// Leads with the pre-registered verdict, then one row per round: exam pass@1 of that round's model, its gain over the
// base and over the round before (paired per exam problem, 95% CI), and what its search and training did.

const DIGITS = 1;
const PVAL_DIGITS = 3; // allow-number: display precision of p-values
const pct = (v) => (v == null || Number.isNaN(v) ? 'n/a' : `${(v * 100).toFixed(DIGITS)}%`);
const pts = (v) => {
  if (v == null || Number.isNaN(v)) return 'n/a';
  const s = (v * 100).toFixed(DIGITS);
  return Number(s) === 0 ? `+${Math.abs(Number(s)).toFixed(DIGITS)}` : `${v > 0 ? '+' : ''}${s}`;
};
const cmp = (d) => (d && d.n ? `${pts(d.estimate)} pts [${pts(d.low)}, ${pts(d.high)}], p ${Number(d.pValue).toFixed(PVAL_DIGITS)}${d.significant ? ' (significant)' : ''}` : 'n/a');

export function verdictLine(spec, v, stop) {
  if (v.status === 'complete') {
    return `**Verdict (round ${v.primaryRound} vs base): ${v.confirmed ? 'recursive self-improvement confirmed' : 'not confirmed'}**: ` +
      `${cmp(v.vsBase)}; beats the base: ${v.beatsBase ? 'yes' : 'no'}; adds to round 1 (${v.firstRoundVsBase ? pts(v.firstRoundVsBase.estimate) : 'n/a'} pts): ${v.compounding ? 'yes' : 'no'}.`;
  }
  if (stop) return `**Verdict: not confirmed**: the loop stopped (${stop}) after round ${v.roundsDone}, before round ${v.primaryRound}.`;
  return `Status: collecting, ${v.roundsDone} of ${v.primaryRound} rounds done (no verdict until round ${v.primaryRound}).`;
}

/** One line for the README block. */
export function rsiSummaryLine(cfg, rounds, verdict, stop) {
  const last = rounds.at(-1);
  if (!last) return `**Recursive self-improvement** ([RSI.md](${cfg.rsi.reportFile})): starting; no round finished yet.`;
  return `**Recursive self-improvement** ([RSI.md](${cfg.rsi.reportFile})): round ${last.round} model scores ${pct(last.exam.passAt1)} on the ${last.exam.problems}-problem exam, ` +
    `${pts(last.vsBase.estimate)} pts vs the untrained model [${pts(last.vsBase.low)}, ${pts(last.vsBase.high)}], ${pts(last.vsPrevious.estimate)} pts vs round ${last.round - 1}. ${verdictLine(cfg.rsi.preregistered, verdict, stop)}`;
}

export function rsiReport(cfg, state, verdict, stop) {
  const spec = cfg.rsi.preregistered;
  const L = ['# Recursive self-improvement (expert iteration in rounds)', ''];
  L.push(`_Generated by \`node src/rsi/cli.js record\` from ${cfg.rsi.stateDir}/. Method: src/rsi/core.js; decision log: DECISIONS.md._`, '');
  L.push(`**Pre-registered** (${spec.registered}): ${spec.hypothesis}`, '', verdictLine(spec, verdict, stop), '');
  L.push(`Each round: the previous round's model searches (${cfg.rsi.search.samples} samples per training problem, kept only if the problem's tests pass), ` +
    `the base model is fine-tuned on all verified solutions found so far, and the new model sits the exam: ${cfg.rsi.eval.samples} single attempts per problem ` +
    `(temperature ${cfg.rsi.eval.temperature}, no search, no tests shown) on ${state.baseExam.problems || 'n/a'} problems that are never searched or trained on. ` +
    `Round 0 is the untrained model through the same conversion and quantization (exam pass@1 ${pct(state.baseExam.passAt1)}).`, '');
  L.push('| Round | Exam pass@1 | vs untrained (95% CI) | vs previous round (95% CI) | Search: solved / searched (own training problems, not evidence) | Training examples (hard) | Train loss first -> last | Run |');
  L.push('|---|---|---|---|---|---|---|---|');
  for (const r of state.rounds) {
    L.push(`| ${r.round} | ${pct(r.exam.passAt1)} (${r.exam.problems}) | ${cmp(r.vsBase)} | ${cmp(r.vsPrevious)} | ${r.search.solved} / ${r.search.problems} (mean pass ${pct(r.search.meanPassFraction)}) | ` +
      `${r.data ? `${r.data.examples} (${r.data.hardProblems} problems)` : 'n/a'} | ${r.train ? `${r.train.lossFirst} -> ${r.train.lossLast} (${r.train.stopped})` : 'n/a'} | ${r.runId ?? 'n/a'} |`);
  }
  L.push('', 'Reading it: a round counts as self-improvement only through the exam columns. The search column is measured on problems the model has trained on, so it rises even without real learning.', '');
  return `${L.join('\n')}\n`;
}
